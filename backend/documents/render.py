"""Template rendering for customer documents.

Templates are HTML written by staff with {{ placeholders }}. Rendering is deliberately
simple and safe: no expressions or code, only whitelisted keys; every value is HTML-escaped;
table blocks are generated by the server. Template HTML is sanitised on save.
"""
